/**
 * Stamps the last commit date into a module at build time.
 *
 * The commit rather than the build, because the page is statically generated
 * with an hourly revalidate for the star count — a `new Date()` in the
 * component would creep forward every hour and claim the site had been
 * updated when nothing had changed. A commit date only moves when the site
 * does.
 *
 * Falls back to the build time where git is unavailable, which is better than
 * failing the build over a footer.
 *
 * It also weighs the built library. A size printed on the page is a claim,
 * and a claim typed by hand is one that goes quietly wrong the first time
 * somebody adds a component — so it is measured from the file that actually
 * ships, every build.
 */
import { execFileSync } from 'node:child_process'
import { gzipSync } from 'node:zlib'
import { readFile, writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

let iso
let source
try {
  iso = execFileSync('git', ['log', '-1', '--format=%cI'], { encoding: 'utf8' }).trim()
  source = 'the last commit'
} catch {
  iso = new Date().toISOString()
  source = 'the build (git was unavailable)'
}

/* The JS, gzipped, which is what a bundle-size claim conventionally means.
   The stylesheet is a separate import and weighed separately. */
const dist = join(root, '..', '..', 'packages', 'yote-ui', 'dist')
const bundleKb = Math.round(gzipSync(await readFile(join(dist, 'index.js'))).length / 1024)
const cssKb = Math.round(gzipSync(await readFile(join(dist, 'styles.css'))).length / 1024)

await writeFile(
  join(root, 'components', 'site-meta.ts'),
  `// Generated by scripts/build-site-meta.mjs. Do not edit.
// Date taken from ${source}; sizes measured from packages/yote-ui/dist.
export const LAST_UPDATED = '${iso}'
export const BUNDLE_KB = ${bundleKb}
export const CSS_KB = ${cssKb}
`,
)
console.log(`last updated: ${iso} · bundle ${bundleKb}KB gzip · css ${cssKb}KB gzip`)
