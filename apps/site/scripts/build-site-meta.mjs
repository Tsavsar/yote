/**
 * Stamps the last commit date into a module at build time.
 *
 * The commit rather than the build, because the page is statically generated
 * with an hourly revalidate for the star count — a `new Date()` in the
 * component would creep forward every hour and claim the site had been
 * updated when nothing had changed. A commit date only moves when the site
 * does.
 *
 * Falls back to the build time where git is unavailable, which is better than
 * failing the build over a footer.
 */
import { execFileSync } from 'node:child_process'
import { writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

let iso
let source
try {
  iso = execFileSync('git', ['log', '-1', '--format=%cI'], { encoding: 'utf8' }).trim()
  source = 'the last commit'
} catch {
  iso = new Date().toISOString()
  source = 'the build (git was unavailable)'
}

await writeFile(
  join(root, 'components', 'site-meta.ts'),
  `// Generated by scripts/build-site-meta.mjs. Do not edit.
// Taken from ${source}.
export const LAST_UPDATED = '${iso}'
`,
)
console.log(`last updated: ${iso}`)
